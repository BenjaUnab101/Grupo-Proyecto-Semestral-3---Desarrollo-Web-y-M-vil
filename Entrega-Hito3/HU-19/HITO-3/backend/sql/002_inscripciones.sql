-- HU-19: actividades (eventos), inscripciones, vista de asistentes y datos de demostración.
-- Docker lo ejecuta solo, después de 001_schema.sql, cuando la base está vacía.
-- Se puede ejecutar varias veces: no duplica tablas ni datos.

CREATE TABLE IF NOT EXISTS actividades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    titulo VARCHAR(160) NOT NULL,
    descripcion TEXT,
    fecha DATE NOT NULL,
    hora TIME,
    lugar VARCHAR(120),
    cupo_maximo INTEGER NOT NULL,
    inscripciones_abiertas BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_actividades_cupo_positivo CHECK (cupo_maximo > 0)
);

CREATE TABLE IF NOT EXISTS inscripciones (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id INTEGER NOT NULL REFERENCES actividades(id) ON DELETE RESTRICT,
    alumno_id INTEGER NOT NULL REFERENCES alumnos(id) ON DELETE RESTRICT,
    apoderado_id INTEGER NOT NULL REFERENCES apoderados(id) ON DELETE RESTRICT,
    estado VARCHAR(20) NOT NULL DEFAULT 'inscrita',
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    cancelada_en TIMESTAMPTZ,
    -- CA3: como máximo una inscripción por alumno y actividad.
    CONSTRAINT uq_inscripcion_actividad_alumno UNIQUE (actividad_id, alumno_id),
    CONSTRAINT ck_inscripcion_estado CHECK (estado IN ('inscrita', 'cancelada'))
);

CREATE INDEX IF NOT EXISTS ix_inscripciones_actividad_estado ON inscripciones(actividad_id, estado);

-- CA4: vista de asistentes por actividad con su estado (para consultas del organizador
-- directamente en SQL). La API hace la misma consulta con SQLAlchemy.
CREATE OR REPLACE VIEW v_asistentes_actividad AS
SELECT
    a.id AS actividad_id,
    a.titulo AS actividad,
    a.fecha,
    a.cupo_maximo,
    i.id AS inscripcion_id,
    al.id AS alumno_id,
    al.codigo AS alumno_codigo,
    al.nombre AS alumno_nombre,
    i.estado,
    i.creada_en,
    i.cancelada_en
FROM inscripciones i
JOIN actividades a ON a.id = i.actividad_id
JOIN alumnos al ON al.id = i.alumno_id;

