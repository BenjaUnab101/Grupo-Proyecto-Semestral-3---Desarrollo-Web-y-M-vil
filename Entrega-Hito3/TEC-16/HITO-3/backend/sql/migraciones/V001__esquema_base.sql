-- y las tablas de HU-17/18/20/27 (categorias_actividad, organizadores, actividades_escolares,
-- inscripciones_pagos, documentos_institucionales). Es el contenido de sql/001_schema.sql.

CREATE TABLE IF NOT EXISTS apoderados (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    rut_hash VARCHAR(255) UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS salas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    nivel VARCHAR(40) NOT NULL,
    capacidad INTEGER NOT NULL DEFAULT 15 CHECK (capacidad > 0),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS alumnos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    fecha_nacimiento DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS apoderados_alumnos (
    apoderado_id INTEGER NOT NULL REFERENCES apoderados(id) ON DELETE CASCADE,
    alumno_id INTEGER NOT NULL REFERENCES alumnos(id) ON DELETE CASCADE,
    parentesco VARCHAR(40) NOT NULL DEFAULT 'Apoderado',
    es_contacto_principal BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (apoderado_id, alumno_id)
);

CREATE TABLE IF NOT EXISTS matriculas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id INTEGER NOT NULL REFERENCES alumnos(id) ON DELETE RESTRICT,
    sala_id INTEGER NOT NULL REFERENCES salas(id) ON DELETE RESTRICT,
    anio_escolar INTEGER NOT NULL CHECK (anio_escolar >= 2020),
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'vigente', 'anulada')),
    CONSTRAINT uq_matricula_alumno_anio UNIQUE (alumno_id, anio_escolar)
);

CREATE INDEX IF NOT EXISTS ix_alumnos_activo ON alumnos(activo);
CREATE INDEX IF NOT EXISTS ix_matriculas_anio ON matriculas(anio_escolar);

CREATE TABLE IF NOT EXISTS categorias_actividad (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS organizadores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    rol_perfil VARCHAR(60) NOT NULL
        CHECK (rol_perfil IN ('Dirección', 'Educadora', 'Fonoaudióloga', 'Coordinación')),
    telefono VARCHAR(30),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS actividades_escolares (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(140) NOT NULL,
    fecha DATE NOT NULL,
    hora VARCHAR(5),
    lugar VARCHAR(120) NOT NULL,
    preparar VARCHAR(255),
    capacidad INTEGER NOT NULL CHECK (capacidad > 0),
    cupos_ocupados INTEGER NOT NULL DEFAULT 0
        CHECK (cupos_ocupados >= 0 AND cupos_ocupados <= capacidad),
    estado VARCHAR(20) NOT NULL DEFAULT 'borrador'
        CHECK (estado IN ('borrador', 'publicada', 'cancelada')),
    categoria_id INTEGER NOT NULL REFERENCES categorias_actividad(id) ON DELETE RESTRICT,
    organizador_id INTEGER NOT NULL REFERENCES organizadores(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_actividades_fecha_estado ON actividades_escolares(fecha, estado);

CREATE TABLE IF NOT EXISTS inscripciones_pagos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_comprobante VARCHAR(60) NOT NULL UNIQUE,
    actividad_id INTEGER NOT NULL REFERENCES actividades_escolares(id) ON DELETE RESTRICT,
    apoderado_rut VARCHAR(20) NOT NULL,
    nombre_parvulo VARCHAR(120) NOT NULL,
    monto INTEGER NOT NULL CHECK (monto >= 0),
    metodo_pago VARCHAR(40) NOT NULL DEFAULT 'Transferencia Simulada',
    estado_pago VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado_pago IN ('pendiente', 'pagado', 'confirmado', 'cancelado')),
    fecha_transaccion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_inscripciones_comprobante ON inscripciones_pagos(codigo_comprobante);

CREATE TABLE IF NOT EXISTS documentos_institucionales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(140) NOT NULL UNIQUE,
    categoria VARCHAR(40) NOT NULL
        CHECK (categoria IN ('Reglamentos', 'Protocolos', 'Formularios')),
    descripcion VARCHAR(500) NOT NULL,
    url_archivo VARCHAR(255),
    vigente BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE INDEX IF NOT EXISTS ix_documentos_categoria_vigente ON documentos_institucionales(categoria, vigente);
