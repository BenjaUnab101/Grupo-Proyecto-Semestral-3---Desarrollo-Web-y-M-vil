-- V006 · HU-16 (Sprint 3 · Daniel): sesiones de inicio de sesión real.
--
-- La tabla usuarios (V003) ya tiene email, password_hash y rol. Aquí se agregan las
-- sesiones que entrega POST /auth/login. Del token solo se guarda su SHA-256: quien lea
-- esta tabla no puede usar las sesiones. Logout = revocada_en con fecha (cierre real en el
-- servidor, no solo en la pantalla).

CREATE TABLE IF NOT EXISTS sesiones (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_en TIMESTAMPTZ NOT NULL,
    revocada_en TIMESTAMPTZ,
    CONSTRAINT ck_sesiones_expiracion CHECK (expira_en > creada_en)
);

CREATE INDEX IF NOT EXISTS ix_sesiones_usuario ON sesiones(usuario_id);
-- Sesiones activas (las que se consultan en cada petición).
CREATE INDEX IF NOT EXISTS ix_sesiones_activas ON sesiones(expira_en) WHERE revocada_en IS NULL;
