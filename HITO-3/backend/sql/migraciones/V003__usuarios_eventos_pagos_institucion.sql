-- V003 · TEC-16: usuarios, categorías, pagos ficticios y datos institucionales.
--
-- Los "eventos" del modelo son las ACTIVIDADES de HU-19 (tabla actividades): aquí se les
-- agrega categoría, organizador y costo, en vez de crear una tabla paralela.
--
-- Todo con IF NOT EXISTS para poder aplicarse también sobre bases creadas antes de las
-- migraciones (volúmenes de Docker existentes).

-- ---------- Datos institucionales del jardín (una sola fila) ----------
CREATE TABLE IF NOT EXISTS institucion (
    id SMALLINT PRIMARY KEY DEFAULT 1,
    nombre VARCHAR(120) NOT NULL,
    tipo VARCHAR(120) NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    comuna VARCHAR(80) NOT NULL,
    region VARCHAR(80) NOT NULL,
    telefono VARCHAR(20),
    email VARCHAR(180),
    horario_atencion VARCHAR(120),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_institucion_fila_unica CHECK (id = 1)
);

-- ---------- Usuarios (cuentas para el futuro inicio de sesión) ----------
CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    apoderado_id INTEGER UNIQUE REFERENCES apoderados(id) ON DELETE RESTRICT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('apoderado', 'organizador', 'administrador')),
    CONSTRAINT ck_usuarios_email_minusculas CHECK (email = lower(email)),
    -- Un usuario con rol apoderado debe estar ligado a un apoderado, y solo ese rol.
    CONSTRAINT ck_usuarios_apoderado_segun_rol CHECK ((rol = 'apoderado') = (apoderado_id IS NOT NULL))
);

-- ---------- Organizadores ----------
-- Se usa la tabla organizadores de V001 (HU-17): nombre, email, rol_perfil, telefono y activo.

-- ---------- Categorías de actividades ----------
CREATE TABLE IF NOT EXISTS categorias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE,
    descripcion VARCHAR(200)
);

-- ---------- Actividades (eventos): categoría, organizador y costo ----------
ALTER TABLE actividades
    ADD COLUMN IF NOT EXISTS categoria_id INTEGER REFERENCES categorias(id) ON DELETE RESTRICT;
ALTER TABLE actividades
    ADD COLUMN IF NOT EXISTS organizador_id INTEGER REFERENCES organizadores(id) ON DELETE RESTRICT;
-- Costo en pesos chilenos, sin decimales. 0 = actividad gratuita.
ALTER TABLE actividades
    ADD COLUMN IF NOT EXISTS costo INTEGER NOT NULL DEFAULT 0
    CONSTRAINT ck_actividades_costo_no_negativo CHECK (costo >= 0);

CREATE INDEX IF NOT EXISTS ix_actividades_fecha ON actividades(fecha);
CREATE INDEX IF NOT EXISTS ix_actividades_categoria ON actividades(categoria_id);
CREATE INDEX IF NOT EXISTS ix_actividades_organizador ON actividades(organizador_id);

-- ---------- Pagos FICTICIOS de inscripciones ----------
-- No existe ningún dato de tarjeta ni de cuenta: el único método posible es 'simulado'.
CREATE TABLE IF NOT EXISTS pagos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscripcion_id INTEGER NOT NULL REFERENCES inscripciones(id) ON DELETE RESTRICT,
    monto INTEGER NOT NULL,
    moneda CHAR(3) NOT NULL DEFAULT 'CLP',
    metodo VARCHAR(20) NOT NULL DEFAULT 'simulado',
    estado VARCHAR(20) NOT NULL DEFAULT 'aprobado',
    referencia VARCHAR(40) NOT NULL UNIQUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_pagos_monto_positivo CHECK (monto > 0),
    CONSTRAINT ck_pagos_moneda CHECK (moneda = 'CLP'),
    CONSTRAINT ck_pagos_metodo_simulado CHECK (metodo = 'simulado'),
    CONSTRAINT ck_pagos_estado CHECK (estado IN ('aprobado', 'reembolsado')),
    CONSTRAINT ck_pagos_referencia_simulada CHECK (referencia LIKE 'SIM-%')
);

-- Una inscripción puede tener como máximo UN pago aprobado (puede tener reembolsados).
CREATE UNIQUE INDEX IF NOT EXISTS uq_pagos_aprobado_por_inscripcion
    ON pagos(inscripcion_id) WHERE estado = 'aprobado';
