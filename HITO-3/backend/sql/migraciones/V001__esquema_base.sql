-- V001 · Esquema base del Hito 3 (apoderados, salas, alumnos, apoderados_alumnos, matriculas).
-- Contenido original de sql/001_schema.sql, sin cambios.

CREATE TABLE IF NOT EXISTS apoderados (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    rut_hash VARCHAR(255) UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS salas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    nivel VARCHAR(40) NOT NULL,
    capacidad INTEGER NOT NULL DEFAULT 15 CHECK (capacidad > 0),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS alumnos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    fecha_nacimiento DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS apoderados_alumnos (
    apoderado_id INTEGER NOT NULL REFERENCES apoderados(id) ON DELETE CASCADE,
    alumno_id INTEGER NOT NULL REFERENCES alumnos(id) ON DELETE CASCADE,
    parentesco VARCHAR(40) NOT NULL DEFAULT 'Apoderado',
    es_contacto_principal BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (apoderado_id, alumno_id)
);

CREATE TABLE IF NOT EXISTS matriculas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id INTEGER NOT NULL REFERENCES alumnos(id) ON DELETE RESTRICT,
    sala_id INTEGER NOT NULL REFERENCES salas(id) ON DELETE RESTRICT,
    anio_escolar INTEGER NOT NULL CHECK (anio_escolar >= 2020),
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'vigente', 'anulada')),
    CONSTRAINT uq_matricula_alumno_anio UNIQUE (alumno_id, anio_escolar)
);

CREATE INDEX IF NOT EXISTS ix_alumnos_activo ON alumnos(activo);
CREATE INDEX IF NOT EXISTS ix_matriculas_anio ON matriculas(anio_escolar);
