-- V005 · HU-25: solicitudes de pre-matrícula con seguimiento.
--
-- Cada solicitud que envía una familia queda guardada con un CÓDIGO DE SEGUIMIENTO
-- (ej. PM-7K3Q9X) y un ESTADO. La familia consulta el estado con su código + su correo;
-- dirección lo cambia. En la demo solo se usan datos ficticios.

CREATE TABLE IF NOT EXISTS solicitudes_prematricula (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(9) NOT NULL UNIQUE,
    nombre_apoderado VARCHAR(80) NOT NULL,
    rut VARCHAR(10) NOT NULL,            -- sin puntos, con guion: 12345678-5
    correo VARCHAR(254) NOT NULL,        -- en minúsculas
    telefono CHAR(9) NOT NULL,           -- 9 dígitos, sin +56: 912345678
    nombre_parvulo VARCHAR(80) NOT NULL,
    nivel VARCHAR(20) NOT NULL,          -- los ids de frontend-react/src/data/niveles.json
    comentario VARCHAR(300),
    consentimiento_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado VARCHAR(20) NOT NULL DEFAULT 'recibida',
    mensaje_familia VARCHAR(300),        -- mensaje de dirección que ve la familia
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_prematricula_nivel CHECK (nivel IN ('medio-menor', 'medio-mayor', 'transicion-1', 'transicion-2', 'sala-tel')),
    CONSTRAINT ck_prematricula_estado CHECK (estado IN ('recibida', 'en_revision', 'lista_espera', 'aceptada', 'rechazada'))
);

-- Una familia no puede tener dos solicitudes EN CURSO para el mismo párvulo y nivel.
-- (Si la anterior ya fue aceptada o rechazada, sí puede volver a postular.)
CREATE UNIQUE INDEX IF NOT EXISTS uq_prematricula_en_curso
    ON solicitudes_prematricula (rut, nombre_parvulo, nivel)
    WHERE estado IN ('recibida', 'en_revision', 'lista_espera');
