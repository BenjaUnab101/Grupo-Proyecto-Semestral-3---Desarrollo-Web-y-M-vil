-- V007 · HU-26 (Sprint 3 · Daniel): consultas de contacto con la dirección.
--
-- Reemplaza la demo del Taller 2 (HU-12, formulario sin envío). Cada consulta queda en
-- PostgreSQL con un CÓDIGO DE SEGUIMIENTO (ej. CT-7K3Q9X) y un ESTADO de atención:
--   nuevo -> en_gestion -> cerrado   (solo dirección los cambia)
-- usuario_id: la cuenta que la envió (NULL si la envió un visitante sin iniciar sesión).
-- En la demo solo se usan datos ficticios.

CREATE TABLE IF NOT EXISTS consultas_contacto (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(9) NOT NULL UNIQUE,
    usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    nombre VARCHAR(80) NOT NULL,
    correo VARCHAR(254) NOT NULL,        -- en minúsculas
    telefono CHAR(9) NOT NULL,           -- 9 dígitos, sin +56
    asunto VARCHAR(100) NOT NULL,
    mensaje VARCHAR(1000) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'nuevo',
    respuesta_direccion VARCHAR(500),    -- lo que ve la familia
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_contacto_estado CHECK (estado IN ('nuevo', 'en_gestion', 'cerrado')),
    CONSTRAINT ck_contacto_mensaje CHECK (char_length(btrim(mensaje)) >= 10),
    CONSTRAINT ck_contacto_correo_minusculas CHECK (correo = lower(correo))
);

CREATE INDEX IF NOT EXISTS ix_contacto_estado_fecha ON consultas_contacto(estado, creada_en DESC);
CREATE INDEX IF NOT EXISTS ix_contacto_usuario ON consultas_contacto(usuario_id, creada_en DESC);
