-- V004 · HU-21: comunicados persistidos en PostgreSQL.
--
-- Hasta ahora los comunicados vivían en MongoDB. Desde HU-21, PostgreSQL es la fuente
-- de verdad; MongoDB guarda la BITÁCORA de cambios (colección bitacora_comunicados).
--
-- Niveles: los mismos de HU-03 (Taller 2): General, Salas TEL y Preescolar.

-- ---------- Grupo de comunicados de cada sala ----------
-- Sirve para saber qué comunicados son pertinentes para un apoderado: los "General" más
-- los del grupo de las salas donde están matriculados sus hijos.
ALTER TABLE salas
    ADD COLUMN IF NOT EXISTS grupo_comunicados VARCHAR(20) NOT NULL DEFAULT 'Preescolar'
    CONSTRAINT ck_salas_grupo_comunicados CHECK (grupo_comunicados IN ('Preescolar', 'Salas TEL'));

-- Las salas existentes cuyo nivel menciona TEL quedan en el grupo "Salas TEL".
UPDATE salas SET grupo_comunicados = 'Salas TEL'
WHERE nivel ILIKE '%TEL%' AND grupo_comunicados <> 'Salas TEL';

-- ---------- Comunicados ----------
CREATE TABLE IF NOT EXISTS comunicados (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(160) NOT NULL,
    cuerpo TEXT NOT NULL,
    nivel VARCHAR(20) NOT NULL,
    alcance VARCHAR(100),
    categoria VARCHAR(50) NOT NULL DEFAULT 'Aviso',
    es_urgente BOOLEAN NOT NULL DEFAULT FALSE,
    publicado BOOLEAN NOT NULL DEFAULT TRUE,
    -- Puede ser futura: el comunicado queda programado y no se muestra hasta esa hora.
    fecha_publicacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Último día (hora de Chile) en que se muestra. NULL = no vence.
    vigente_hasta DATE,
    autor_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_comunicados_nivel CHECK (nivel IN ('General', 'Salas TEL', 'Preescolar')),
    CONSTRAINT ck_comunicados_titulo CHECK (char_length(btrim(titulo)) >= 3),
    CONSTRAINT ck_comunicados_cuerpo CHECK (char_length(btrim(cuerpo)) >= 1 AND char_length(cuerpo) <= 10000),
    CONSTRAINT ck_comunicados_vigencia CHECK (
        vigente_hasta IS NULL
        OR vigente_hasta >= (fecha_publicacion AT TIME ZONE 'America/Santiago')::date
    )
);

-- Listado de vigentes por fecha (el caso más frecuente) y filtros por nivel y urgencia.
CREATE INDEX IF NOT EXISTS ix_comunicados_publicados_fecha
    ON comunicados (fecha_publicacion DESC) WHERE publicado;
CREATE INDEX IF NOT EXISTS ix_comunicados_nivel_fecha
    ON comunicados (nivel, fecha_publicacion DESC);
CREATE INDEX IF NOT EXISTS ix_comunicados_urgentes
    ON comunicados (fecha_publicacion DESC) WHERE es_urgente;
